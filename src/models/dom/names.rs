macro_rules! local_names {
    ($($name:ident = $text:literal,)*) => {
        /// Element names that parsing rules refer to, interned so the tree builder
        /// matches integers instead of strings.
        #[derive(Clone, Copy, PartialEq, Eq, Debug)]
        pub(super) enum LocalName {
            $($name,)*
            Other,
        }

        impl LocalName {
            /// Common email tags come first, as each name is compared in turn.
            pub(super) fn new(name: &str) -> Self {
                match name {
                    $($text => Self::$name,)*
                    _ => Self::Other,
                }
            }

            pub(super) fn text(self) -> &'static str {
                match self {
                    $(Self::$name => $text,)*
                    Self::Other => unreachable!("unknown names keep their own text"),
                }
            }
        }
    };
}

